#!/usr/bin/env python3
"""Prepare a sign test case: closed tank (no inflow), stable linear T profile
(20 C bottom -> 60 C top), uniform k = 1e-4 m2/s2 and omega = 1 1/s everywhere.
Usage: sign_test.py <case>   (case already generated by make_tank_case.py --uin 0)"""
import re
import sys

c = sys.argv[1]
unstable = len(sys.argv) > 2 and sys.argv[2] == "unstable"
for name, val in (("k", "1e-4"), ("omega", "1")):
    p = f"{c}/0/{name}"
    s = open(p).read()
    s = re.sub(r"uniform [0-9.eE+-]+", f"uniform {val}", s)
    open(p, "w").write(s)
open(f"{c}/system/setExprFieldsDict", "w").write("""FoamFile { version 2.0; format ascii; class dictionary; object setExprFieldsDict; }
expressions
(
    T
    {
        field       T;
        dimensions  [0 0 0 1 0 0 0];
        expression  #{ EXPR #};
    }
);
""".replace("EXPR", "333.15 - 40*pos().y()" if unstable else "293.15 + 40*pos().y()"))
