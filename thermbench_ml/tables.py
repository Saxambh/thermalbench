"""Benchmark tables from results/<split>.json: one table per metric, models x splits.
Seeds of one neural model (fno, fno_s1, fno_s2, ...) are pooled into mean +- sd.

  python tables.py            -> prints markdown and writes results/tables.md + results/summary.csv
"""
import csv
import glob
import json
import os
import re
from collections import defaultdict

import numpy as np

from evaluate import COLS
from splits import SPLITS

HERE = os.path.dirname(os.path.abspath(__file__))
ORDER = ["initial", "ideal_stratified", "knn", "fno", "unet", "fno_hybrid", "unet_hybrid"]
UNITS = {"rmse_K": "K", "rmse_theta": "-", "profile_rmse": "-", "y_mid_err_m": "m",
         "energy_err": "fraction of full capacity", "T_out_err_K": "K"}


def collect():
    """{(model, split): [value dicts, one per seed]} and split sizes."""
    vals, sizes = defaultdict(list), {}
    for f in glob.glob(os.path.join(HERE, "results", "*.json")):
        d = json.load(open(f))
        sizes[d["split"]] = d.get("sizes", {})
        for name, r in d["results"].items():
            vals[(re.sub(r"_s\d+$", "", name), d["split"])].append(r)
    return vals, sizes


def main():
    vals, sizes = collect()
    splits = [s for s in SPLITS if s in sizes]
    models = [m for m in ORDER if any((m, s) in vals for s in splits)]
    lines = ["# ThermBench results (auto-generated by tables.py)", "",
             "Test runs per split: " + ", ".join(f"{s} {sizes[s].get('test', 0)}" for s in splits), "",
             "Neural models: mean +- sd over seeds (n). Field errors below ~0.65-2 K are within the "
             "CFD noise floor (chaotic buoyant jet).", ""]
    rows = []
    for c in COLS:
        lines += [f"## {c} ({UNITS[c]})", "", "| model | " + " | ".join(splits) + " |",
                  "|---|" + "---|" * len(splits)]
        for m in models:
            cells = []
            for s in splits:
                v = np.array([r[c] for r in vals.get((m, s), [])], float)
                if v.size == 0:
                    cells.append("")
                    continue
                cells.append(f"{v.mean():.3f}" if v.size == 1 else f"{v.mean():.3f} +- {v.std():.3f} ({v.size})")
                rows.append({"metric": c, "model": m, "split": s, "mean": v.mean(),
                             "sd": v.std() if v.size > 1 else "", "n_seeds": v.size})
            lines.append(f"| {m} | " + " | ".join(cells) + " |")
        lines.append("")
    text = "\n".join(lines)
    print(text)
    open(os.path.join(HERE, "results", "tables.md"), "w").write(text)
    with open(os.path.join(HERE, "results", "summary.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["metric", "model", "split", "mean", "sd", "n_seeds"])
        w.writeheader()
        w.writerows(rows)


if __name__ == "__main__":
    main()
