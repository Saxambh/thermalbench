"""Benchmark tables from <results>/<split>.json: one table per metric, models x splits, plus the
2 x 2 ablation (physics base x canonical frame) per architecture on the main metric (tank).
Seeds of one neural model (fno, fno_s1, fno_s2, ...) are pooled into mean +- sd.

  python tables.py [--results results] [--family tank|pcm]
      -> prints markdown and writes <results>/tables.md + <results>/summary.csv
Updated 2026-11-04: all eight tank models (canonical-frame variants), the PCM benchmark, a
results folder argument (merged results of the GPU workers), best mean per split in bold.
"""
import argparse
import csv
import glob
import json
import os
import re
from collections import defaultdict

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
FAMILY = {
    "tank": {
        "order": ["initial", "ideal_stratified", "knn", "nn", "idw", "rbf", "fno", "fno_canon", "fno_hybrid", "fno_hybrid_canon",
                  "unet", "unet_canon", "unet_hybrid", "unet_hybrid_canon"],
        "units": {"rmse_K": "K", "rmse_theta": "-", "profile_rmse": "-", "y_mid_err_m": "m",
                  "energy_err": "fraction of full capacity", "T_out_err_K": "K"},
        "note": "Field errors below ~0.65-2 K are within the CFD noise floor (chaotic buoyant jet).",
    },
    "pcm": {
        "order": ["initial", "stefan", "front", "knn", "nn", "idw", "rbf", "fno", "fno_hybrid", "unet", "unet_hybrid"],
        "units": {"rmse_K": "K", "alpha_rmse": "-", "liquid_iou": "- (higher is better)", "melt_frac_err": "-",
                  "energy_err": "fraction of full charge", "t90_err": "fraction of t90, runs that reach 90 % only", "t90_reached": "share of runs reaching 90 % melted"},
        "note": "",
    },
}
HIGHER_BETTER = {"liquid_iou", "r2_field"}


def splits_of(family):
    if family == "pcm":
        from pcm_splits import SPLITS
    else:
        from splits import SPLITS
    return SPLITS


def collect(results):
    """{(model, split): [value dicts, one per seed]} and split sizes."""
    vals, sizes = defaultdict(list), {}
    for f in glob.glob(os.path.join(HERE, results, "*.json")):
        d = json.load(open(f))
        if "split" not in d or "results" not in d:
            continue
        sizes[d["split"]] = d.get("sizes", {})
        for name, r in d["results"].items():
            vals[(re.sub(r"_s\d+$", "", name), d["split"])].append(r)
    return vals, sizes


def stat(vals, m, s, c):
    return np.array([r[c] for r in vals.get((m, s), []) if c in r], float)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--family", default="tank", choices=FAMILY)
    a = ap.parse_args()
    F = FAMILY[a.family]
    vals, sizes = collect(a.results)
    splits = [s for s in splits_of(a.family) if s in sizes]
    known = F["order"] + sorted({m for m, _ in vals} - set(F["order"]))
    models = [m for m in known if any((m, s) in vals for s in splits)]
    lines = [f"# ThermalStorageBench {a.family} results (auto-generated by tables.py from {a.results}/)", "",
             "Test runs per split: " + ", ".join(f"{s} {sizes[s].get('test', 0)}" for s in splits), "",
             "Neural models: mean +- sd over seeds (n). Best mean per split in bold. " + F["note"], ""]
    rows = []
    for c, unit in F["units"].items():
        best = {}
        for s in splits:
            means = {m: stat(vals, m, s, c).mean() for m in models if stat(vals, m, s, c).size}
            if means:
                best[s] = (max if c in HIGHER_BETTER else min)(means, key=means.get)
        lines += [f"## {c} ({unit})", "", "| model | " + " | ".join(splits) + " |", "|---|" + "---|" * len(splits)]
        for m in models:
            cells = []
            for s in splits:
                v = stat(vals, m, s, c)
                if v.size == 0:
                    cells.append(""); continue
                t = f"{v.mean():.3f}" if v.size == 1 else f"{v.mean():.3f} +- {v.std():.3f} ({v.size})"
                cells.append(f"**{t}**" if best.get(s) == m else t)
                rows.append({"family": a.family, "metric": c, "model": m, "split": s, "mean": v.mean(),
                             "sd": v.std() if v.size > 1 else "", "n_seeds": v.size})
            lines.append(f"| {m} | " + " | ".join(cells) + " |")
        lines.append("")
    if a.family == "tank":   # 2 x 2 ablation on the main metric
        lines += ["## Ablation: physics base x canonical frame (rmse_K, K)", ""]
        for arch in ("fno", "unet"):
            lines += [f"**{arch}**", "", "| split | plain | + canonical frame | + physics base | + both |",
                      "|---|---|---|---|---|"]
            for s in splits:
                cells = []
                for m in (arch, f"{arch}_canon", f"{arch}_hybrid", f"{arch}_hybrid_canon"):
                    v = stat(vals, m, s, "rmse_K")
                    cells.append(f"{v.mean():.3f}" if v.size else "")
                lines.append(f"| {s} | " + " | ".join(cells) + " |")
            lines.append("")
    text = "\n".join(lines)
    print(text)
    os.makedirs(os.path.join(HERE, a.results), exist_ok=True)
    open(os.path.join(HERE, a.results, "tables.md"), "w").write(text)
    with open(os.path.join(HERE, a.results, "summary.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["family", "metric", "model", "split", "mean", "sd", "n_seeds"])
        w.writeheader(); w.writerows(rows)


if __name__ == "__main__":
    main()
